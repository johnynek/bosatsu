#!/usr/bin/env python3
"""Compile separate Bosatsu groups and run their emitted C with the CI runtime."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
HEADER = "bosatsu_ext_Demo_l_Native.h"


def exercise(jar: Path, cc_conf: Path, work: Path) -> None:
    # Only the separate native compile/link operation receives cc_conf.
    cc = json.loads(cc_conf.read_text())
    java = shutil.which("java")
    if not java:
        raise RuntimeError("java is required")

    producer = work / "producer"
    action = work / "action"
    empty_path = work / "empty-path"
    for directory in (producer, action, empty_path):
        directory.mkdir()
    java_env = dict(os.environ, PATH=str(empty_path))

    def tool(cwd: Path, *args: str) -> None:
        subprocess.run([java, "-jar", str(jar), "tool", *args], cwd=cwd,
                       env=java_env, check=True)

    def compile_group(out: str, sources: list[str], deps: list[str]) -> None:
        args = ["compile-packages", "--packages-out", out + ".pkg",
                "--sig-out", out + ".sig", "--error-unused-interfaces"]
        for name in sources:
            args.extend(["--src", name + ".bosatsu"])
        for name in deps:
            args.extend(["--direct-interface", name + ".sig"])
        tool(producer, *args)
        shutil.copyfile(producer / (out + ".pkg"), action / (out + ".pkg"))

    shutil.copyfile(ROOT / "test_workspace/Prog.bosatsu", producer / "Prog.bosatsu")
    (producer / "Native.bosatsu").write_text(
        "package Demo/Native\nexport native_id\nexternal def native_id(x: Int) -> Int\n"
    )
    (producer / "Dep.bosatsu").write_text(
        "package Demo/Dep\nfrom Demo/Native import native_id\nexport answer\n"
        "answer = native_id(7)\nchecks = Assertion(False, \"dependency must not run\")\n"
    )
    plain = (
        "package Demo/Plain\nfrom Demo/Dep import answer\n"
        "def private_check(x): x matches 7\n"
        "checks = Assertion(private_check(answer), \"plain expectation\")\n"
    )
    prog = (
        "package Demo/Effect\nfrom Bosatsu/Prog import ProgTest, pure\n"
        "checks = ProgTest(_ -> pure(Assertion(True, \"effect expectation\")))\n"
    )
    compile_group("prog", ["Prog"], [])
    compile_group("native", ["Native"], [])
    compile_group("dep", ["Dep"], ["native"])

    manifest = {
        "schema_version": 1, "kind": "local",
        "packages": ["dep.pkg", "suite.pkg", "native.pkg", "prog.pkg"],
        "externals": [
            {"package": "Demo/Native", "symbols": ["native_id"]},
            {"package": "Bosatsu/Prog", "symbols": ["pure"]},
        ],
    }
    (action / "runtime.json").write_text(json.dumps(manifest))

    # Compile the user's C binding against the header actually declared and
    # generated by this action, including Bosatsu's underscore mangling.
    binding = work / "binding.c"
    binding.write_text(
        f'#include "{HEADER}"\n'
        'BValue ___bsts_g_Demo_l_Native_l_native__id(BValue x) { return x; }\n'
    )
    for plain_ok, prog_ok in [(True, True), (False, True), (True, False)]:
        (producer / "Plain.bosatsu").write_text(
            plain if plain_ok else plain.replace("matches 7", "matches 8")
        )
        (producer / "Effect.bosatsu").write_text(
            prog if prog_ok else prog.replace("Assertion(True", "Assertion(False")
        )
        compile_group("suite", ["Plain", "Effect"], ["dep", "prog"])
        tool(action, "emit-c", "--test-packages", "suite.pkg",
             "--runtime-manifest", "runtime.json", "--out", "test.c",
             "--extern-header-out", "include/" + HEADER)
        subprocess.run(
            [cc["cc_path"], *cc["flags"], *cc["iflags"], "-I", action / "include",
             action / "test.c", binding, *cc["libs"], "-o", work / "suite"],
            check=True,
        )
        result = subprocess.run([work / "suite"], cwd=work, capture_output=True, text=True, timeout=60)
        report = result.stdout + result.stderr
        expected = 0 if plain_ok and prog_ok else 1
        if result.returncode != expected:
            raise AssertionError(f"expected exit {expected}, got {result.returncode}\n{report}")
        for suite in ("Demo/Plain", "Demo/Effect"):
            if suite not in report:
                raise AssertionError(f"missing suite {suite}\n{report}")
        if "Demo/Dep" in report or "dependency must not run" in report:
            raise AssertionError(f"ran tests outside the selected group\n{report}")
        if not plain_ok and "plain expectation" not in report:
            raise AssertionError(report)
        if not prog_ok and "effect expectation" not in report:
            raise AssertionError(report)
        print(f"native suite passed fixture with plain={plain_ok}, prog={prog_ok}, exit={expected}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jar", type=Path, required=True)
    parser.add_argument("--cc-conf", type=Path, required=True)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="bosatsu-emit-c-") as tmp:
        exercise(args.jar.resolve(), args.cc_conf.resolve(), Path(tmp))
