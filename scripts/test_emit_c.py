#!/usr/bin/env python3
"""Compile separate Bosatsu groups and run their emitted C with the CI runtime."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
HEADER = "bosatsu_ext_Demo_l_Native.h"
PROG_HEADER = "bosatsu_ext_Bosatsu_l_Prog.h"
RUNNER_HEADER = "bosatsu_ext_Demo_l_Runner.h"


def exercise(jar: Path, cc_conf: Path, work: Path) -> None:
    # Only the separate native compile/link operation receives cc_conf.
    cc = json.loads(cc_conf.read_text())
    java_path = shutil.which("java")
    if not java_path:
        raise RuntimeError("java is required")
    java = Path(java_path).resolve()

    producer = work / "producer"
    action = work / "action"
    program_action = work / "program-action"
    empty_path = work / "empty-path"
    for directory in (producer, action, program_action, empty_path):
        directory.mkdir()
    java_env = dict(os.environ, PATH=str(empty_path))

    def tool(cwd: Path, *args: str) -> None:
        subprocess.run([java, "-jar", str(jar), "tool", *args], cwd=cwd,
                       env=java_env, check=True)

    def compile_group(
        out: str, sources: list[str], deps: list[str], destination: Path = action
    ) -> None:
        args = ["compile-packages", "--packages-out", out + ".pkg",
                "--sig-out", out + ".sig", "--error-unused-interfaces"]
        for name in sources:
            args.extend(["--src", name + ".bosatsu"])
        for name in deps:
            args.extend(["--direct-interface", name + ".sig"])
        tool(producer, *args)
        shutil.copyfile(producer / (out + ".pkg"), destination / (out + ".pkg"))

    shutil.copyfile(ROOT / "test_workspace/Prog.bosatsu", producer / "Prog.bosatsu")
    (producer / "Native.bosatsu").write_text(
        "package Demo/Native\nexport native_id\nexternal def native_id(x: Int) -> Int\n"
    )
    (producer / "Dep.bosatsu").write_text(
        "package Demo/Dep\nfrom Demo/Native import native_id\nexport answer\n"
        "answer = native_id(7)\nchecks = Assertion(False, \"dependency must not run\")\n"
    )
    plain = (
        "package Demo/Plain\nfrom Demo/Dep import answer\n"
        "def private_check(x): x matches 7\n"
        "checks = Assertion(private_check(answer), \"plain expectation\")\n"
    )
    prog = (
        "package Demo/Effect\nfrom Bosatsu/Prog import ProgTest, pure\n"
        "checks = ProgTest(_ -> pure(Assertion(True, \"effect expectation\")))\n"
    )
    compile_group("prog", ["Prog"], [])
    compile_group("native", ["Native"], [])
    compile_group("dep", ["Dep"], ["native"])

    manifest = {
        "schema_version": 1, "kind": "local",
        "packages": ["dep.pkg", "suite.pkg", "native.pkg", "prog.pkg"],
        "externals": [
            {"package": "Demo/Native", "symbols": ["native_id"]},
            {"package": "Bosatsu/Prog", "symbols": ["pure"]},
        ],
    }
    (action / "runtime.json").write_text(json.dumps(manifest))

    # Compile the user's C binding against the header actually declared and
    # generated by this action, including Bosatsu's underscore mangling.
    binding = work / "binding.c"
    binding.write_text(
        f'#include "{HEADER}"\n'
        'BValue ___bsts_g_Demo_l_Native_l_native__id(BValue x) { return x; }\n'
    )
    for plain_ok, prog_ok in [(True, True), (False, True), (True, False)]:
        (producer / "Plain.bosatsu").write_text(
            plain if plain_ok else plain.replace("matches 7", "matches 8")
        )
        (producer / "Effect.bosatsu").write_text(
            prog if prog_ok else prog.replace("Assertion(True", "Assertion(False")
        )
        compile_group("suite", ["Plain", "Effect"], ["dep", "prog"])
        tool(action, "emit-c", "--test-packages", "suite.pkg",
             "--runtime-manifest", "runtime.json", "--out", "test.c",
             "--extern-header-out", "include/" + HEADER)
        subprocess.run(
            [cc["cc_path"], *cc["flags"], "-Werror=implicit-function-declaration",
             "-I", action / "include", *cc["iflags"],
             action / "test.c", binding, *cc["libs"], "-o", work / "suite"],
            check=True,
        )
        result = subprocess.run([work / "suite"], cwd=work, capture_output=True, text=True, timeout=60)
        report = result.stdout + result.stderr
        expected = 0 if plain_ok and prog_ok else 1
        if result.returncode != expected:
            raise AssertionError(f"expected exit {expected}, got {result.returncode}\n{report}")
        for suite in ("Demo/Plain", "Demo/Effect"):
            if suite not in report:
                raise AssertionError(f"missing suite {suite}\n{report}")
        if "Demo/Dep" in report or "dependency must not run" in report:
            raise AssertionError(f"ran tests outside the selected group\n{report}")
        if not plain_ok and "plain expectation" not in report:
            raise AssertionError(report)
        if not prog_ok and "effect expectation" not in report:
            raise AssertionError(report)
        print(f"native suite passed fixture with plain={plain_ok}, prog={prog_ok}, exit={expected}")

    # Program emission is a separate file-only action with one selected root
    # bundle and the dependency bundles needed to typecheck and run it.
    (producer / "Types.bosatsu").write_text(
        "package Demo/Types\nexport Result(), get\nstruct Result(value: Int)\n"
        "def get(result: Result) -> Int:\n  match result:\n    case Result(value): value\n"
    )
    (producer / "Api.bosatsu").write_text(
        "package Demo/Api\nfrom Demo/Types import Result, get\n"
        "export result, result_value\nexposes Demo/Types\n"
        "result = Result(7)\nresult_value = value -> get(value)\n"
    )
    (producer / "Main.bosatsu").write_text(
        "package Demo/Main\nfrom Bosatsu/Prog import Main, pure\n"
        "from Demo/Api import result, result_value\n"
        "main = Main(_ -> pure(result_value(result)))\n"
    )
    compile_group("types", ["Types"], [], program_action)
    compile_group("api", ["Api"], ["types"], program_action)
    shutil.copyfile(action / "prog.pkg", program_action / "prog.pkg")
    compile_group("main", ["Main"], ["api", "types", "prog"], program_action)

    program_manifest = {
        "schema_version": 1, "kind": "local",
        "packages": ["prog.pkg", "types.pkg", "api.pkg", "main.pkg"],
        "externals": [{"package": "Bosatsu/Prog", "symbols": ["pure"]}],
    }
    (program_action / "runtime.json").write_text(json.dumps(program_manifest))
    emit_args = [
        "emit-c", "--main-packages", "main.pkg", "--main-package", "Demo/Main",
        "--runtime-manifest", "runtime.json", "--out", "program.c",
        "--extern-header-out", "include/" + PROG_HEADER,
    ]
    tool(program_action, *emit_args)
    expected_files = {
        "runtime.json", "prog.pkg", "types.pkg", "api.pkg", "main.pkg",
        "program.c", "include/" + PROG_HEADER,
    }
    emitted_files = {
        path.relative_to(program_action).as_posix()
        for path in program_action.rglob("*") if path.is_file()
    }
    if emitted_files != expected_files:
        raise AssertionError(f"unexpected program action files: {sorted(emitted_files)}")
    if (program_action / ".bosatsuc").exists():
        raise AssertionError("program emission installed a runtime")
    generated = (program_action / "program.c").read_bytes()

    program_manifest["packages"] = list(reversed(program_manifest["packages"]))
    (program_action / "runtime.json").write_text(json.dumps(program_manifest))
    tool(program_action, *emit_args)
    if (program_action / "program.c").read_bytes() != generated:
        raise AssertionError("reordered program manifest changed generated C")

    # Linking is deliberately separate from emission and receives the C
    # compiler configuration only here.
    executable = work / "program"
    subprocess.run(
        [cc["cc_path"], *cc["flags"], "-Werror=implicit-function-declaration",
         "-I", program_action / "include", *cc["iflags"],
         program_action / "program.c", *cc["libs"], "-o", executable],
        check=True,
    )
    result = subprocess.run([executable], cwd=work, capture_output=True, text=True, timeout=60)
    if result.returncode != 7:
        raise AssertionError(
            f"expected program exit 7, got {result.returncode}\n{result.stdout}{result.stderr}"
        )
    print("native program passed bundle-only emission fixture with exit=7")

    # A second root obtains its Prog value from a reachable package external.
    # It has no reachable Bosatsu/Prog external, so the shared main renderer
    # must declare the native runner independently of generated Prog headers.
    (producer / "Runner.bosatsu").write_text(
        "package Demo/Runner\nfrom Bosatsu/Prog import Prog\nexport make_prog\n"
        "exposes Bosatsu/Prog\n"
        "external def make_prog[err](ignored: Int) -> Prog[err, Int]\n"
    )
    (producer / "RunnerMain.bosatsu").write_text(
        "package Demo/RunnerMain\nfrom Bosatsu/Prog import Main\n"
        "from Demo/Runner import make_prog\nmain = Main(_ -> make_prog(0))\n"
    )
    compile_group("runner", ["Runner"], ["prog"], program_action)
    compile_group("runner-main", ["RunnerMain"], ["runner", "prog"], program_action)
    runner_manifest = {
        "schema_version": 1, "kind": "local",
        "packages": ["prog.pkg", "runner.pkg", "runner-main.pkg"],
        "externals": [{"package": "Demo/Runner", "symbols": ["make_prog"]}],
    }
    (program_action / "runner-runtime.json").write_text(json.dumps(runner_manifest))
    runner_include = "runner-include"
    tool(
        program_action,
        "emit-c", "--main-packages", "runner-main.pkg", "--main-package",
        "Demo/RunnerMain", "--runtime-manifest", "runner-runtime.json",
        "--out", "runner-program.c", "--extern-header-out",
        runner_include + "/" + RUNNER_HEADER,
    )
    runner_program_c = (program_action / "runner-program.c").read_text()
    if PROG_HEADER in runner_program_c:
        raise AssertionError("provider-backed program unexpectedly uses a Prog external")
    if not (program_action / runner_include / RUNNER_HEADER).is_file():
        raise AssertionError("provider external header was not emitted")
    runner_binding = work / "runner_binding.c"
    runner_binding.write_text(
        f'#include "{RUNNER_HEADER}"\n'
        f'#include "{PROG_HEADER}"\n'
        "BValue ___bsts_g_Demo_l_Runner_l_make__prog(BValue ignored) {\n"
        "    (void)ignored;\n"
        "    return ___bsts_g_Bosatsu_l_Prog_l_pure(bsts_integer_from_int(7));\n"
        "}\n"
    )
    runner_executable = work / "runner-program"
    subprocess.run(
        [cc["cc_path"], *cc["flags"], "-Werror=implicit-function-declaration",
         "-I", program_action / runner_include, *cc["iflags"],
         program_action / "runner-program.c", runner_binding, *cc["libs"],
         "-o", runner_executable],
        check=True,
    )
    result = subprocess.run(
        [runner_executable], cwd=work, capture_output=True, text=True, timeout=60
    )
    if result.returncode != 7:
        raise AssertionError(
            f"expected provider-backed program exit 7, got {result.returncode}\n"
            f"{result.stdout}{result.stderr}"
        )
    print("native provider-backed program passed bundle-only emission fixture with exit=7")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jar", type=Path, required=True)
    parser.add_argument("--cc-conf", type=Path, required=True)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="bosatsu-emit-c-") as tmp:
        exercise(args.jar.resolve(), args.cc_conf.resolve(), Path(tmp))
